"""Translate a deliberately bounded Python 3 AST into C11 source."""

from __future__ import annotations

import ast
import json
from dataclasses import dataclass, field
from typing import Iterable

from .runtime import RUNTIME


class CompileError(Exception):
    """A source-level error explaining unsupported Python syntax."""

    def __init__(self, message: str, node: ast.AST | None = None):
        location = ""
        if node is not None and hasattr(node, "lineno"):
            location = f" at line {node.lineno}, column {node.col_offset + 1}"
        super().__init__(f"{message}{location}")


def compile_source(source: str, filename: str = "<input>") -> str:
    """Return C11 source for a supported Python program."""
    try:
        tree = ast.parse(source, filename=filename)
    except SyntaxError as exc:
        raise CompileError(f"Python syntax error: {exc.msg}") from exc
    generator = CGenerator()
    return generator.generate(tree)


@dataclass
class Scope:
    names: set[str] = field(default_factory=set)
    parameters: set[str] = field(default_factory=set)


class CGenerator:
    def __init__(self) -> None:
        self.lines: list[str] = []
        self.indent = 0
        self.scope = Scope()
        self.in_function = False
        self.function_names: set[str] = set()

    def generate(self, tree: ast.Module) -> str:
        self.function_names = {node.name for node in tree.body if isinstance(node, ast.FunctionDef)}
        self.emit("/* Generated by python-to-c-transpiler. Do not edit manually. */")
        self.emit(RUNTIME.rstrip())
        self.emit("")
        functions = [node for node in tree.body if isinstance(node, ast.FunctionDef)]
        for function in functions:
            self.emit(self.function_signature(function) + ";")
        if functions:
            self.emit("")
        for function in functions:
            self.emit_function(function)
            self.emit("")
        self.emit("int main(void) {")
        self.indent += 1
        self.scope = Scope(names=self.collect_assigned(tree.body))
        for name in sorted(self.scope.names):
            self.emit(f"PyValue {self.ident(name)} = py_none();")
        for node in tree.body:
            if not isinstance(node, ast.FunctionDef):
                self.emit_stmt(node)
        self.emit("return 0;")
        self.indent -= 1
        self.emit("}")
        return "\n".join(self.lines) + "\n"

    def emit_function(self, node: ast.FunctionDef) -> None:
        if node.decorator_list:
            raise CompileError("decorators are not supported", node)
        if node.args.vararg or node.args.kwarg or node.args.kwonlyargs or node.args.defaults:
            raise CompileError("only required positional function arguments are supported", node)
        previous_scope, previous_in_function = self.scope, self.in_function
        params = {arg.arg for arg in node.args.args}
        locals_ = self.collect_assigned(node.body) - params
        self.scope = Scope(names=locals_ | params, parameters=params)
        self.in_function = True
        self.emit(self.function_signature(node) + " {")
        self.indent += 1
        for name in sorted(locals_):
            self.emit(f"PyValue {self.ident(name)} = py_none();")
        for statement in node.body:
            self.emit_stmt(statement)
        self.emit("return py_none();")
        self.indent -= 1
        self.emit("}")
        self.scope, self.in_function = previous_scope, previous_in_function

    def function_signature(self, node: ast.FunctionDef) -> str:
        arguments = ", ".join(f"PyValue {self.ident(arg.arg)}" for arg in node.args.args) or "void"
        return f"PyValue {self.ident(node.name)}({arguments})"

    def emit_stmt(self, node: ast.stmt) -> None:
        if isinstance(node, ast.Assign):
            if len(node.targets) != 1 or not isinstance(node.targets[0], ast.Name):
                raise CompileError("only assignment to one variable is supported", node)
            self.emit(f"{self.ident(node.targets[0].id)} = {self.expr(node.value)};")
        elif isinstance(node, ast.AugAssign):
            if not isinstance(node.target, ast.Name):
                raise CompileError("augmented assignment target must be a variable", node)
            op = {ast.Add: "py_add", ast.Sub: "py_sub", ast.Mult: "py_mul", ast.Div: "py_div", ast.Mod: "py_mod"}.get(type(node.op))
            if not op:
                raise CompileError("unsupported augmented-assignment operator", node)
            name = self.ident(node.target.id)
            self.emit(f"{name} = {op}({name}, {self.expr(node.value)});")
        elif isinstance(node, ast.Expr):
            if isinstance(node.value, ast.Call) and isinstance(node.value.func, ast.Name) and node.value.func.id == "print":
                self.emit_print(node.value)
            else:
                self.emit(f"{self.expr(node.value)};")
        elif isinstance(node, ast.If):
            self.emit(f"if ({self.condition(node.test)}) {{")
            self.block(node.body)
            if node.orelse:
                self.emit("} else {")
                self.block(node.orelse)
            self.emit("}")
        elif isinstance(node, ast.While):
            self.emit(f"while ({self.condition(node.test)}) {{")
            self.block(node.body)
            self.emit("}")
            if node.orelse:
                raise CompileError("loop else clauses are not supported", node)
        elif isinstance(node, ast.For):
            self.emit_for(node)
        elif isinstance(node, ast.Return):
            if not self.in_function:
                raise CompileError("return is only valid inside a function", node)
            self.emit(f"return {self.expr(node.value) if node.value else 'py_none()'};")
        elif isinstance(node, ast.Break):
            self.emit("break;")
        elif isinstance(node, ast.Continue):
            self.emit("continue;")
        elif isinstance(node, ast.Pass):
            self.emit("/* pass */")
        elif isinstance(node, ast.FunctionDef):
            raise CompileError("nested functions are not supported", node)
        else:
            raise CompileError(f"unsupported statement: {type(node).__name__}", node)

    def emit_for(self, node: ast.For) -> None:
        if not isinstance(node.target, ast.Name):
            raise CompileError("for-loop target must be one variable", node)
        if not (isinstance(node.iter, ast.Call) and isinstance(node.iter.func, ast.Name) and node.iter.func.id == "range"):
            raise CompileError("only for-loops over range(...) are supported", node)
        args = node.iter.args
        if not 1 <= len(args) <= 3 or node.iter.keywords:
            raise CompileError("range expects one to three positional arguments", node.iter)
        start, stop, step = ("py_int(0)", self.expr(args[0]), "py_int(1)") if len(args) == 1 else (
            (self.expr(args[0]), self.expr(args[1]), "py_int(1)") if len(args) == 2 else (self.expr(args[0]), self.expr(args[1]), self.expr(args[2]))
        )
        variable = self.ident(node.target.id)
        self.emit(f"for ({variable} = {start}; (({step}).i >= 0 ? {variable}.i < ({stop}).i : {variable}.i > ({stop}).i); {variable} = py_add({variable}, {step})) {{")
        self.block(node.body)
        self.emit("}")
        if node.orelse:
            raise CompileError("loop else clauses are not supported", node)

    def emit_print(self, node: ast.Call) -> None:
        """Generate Python-like print output for positional arguments and sep/end."""
        allowed_keywords = {keyword.arg for keyword in node.keywords}
        if None in allowed_keywords or not allowed_keywords <= {"sep", "end"}:
            raise CompileError("print only supports the sep and end keyword arguments", node)
        keywords = {keyword.arg: keyword.value for keyword in node.keywords}
        separator = self.expr(keywords["sep"]) if "sep" in keywords else 'py_str(" ")'
        ending = self.expr(keywords["end"]) if "end" in keywords else 'py_str("\\n")'
        for position, argument in enumerate(node.args):
            if position:
                self.emit(f"py_print({separator});")
            self.emit(f"py_print({self.expr(argument)});")
        self.emit(f"py_print({ending});")

    def block(self, statements: Iterable[ast.stmt]) -> None:
        self.indent += 1
        for statement in statements:
            self.emit_stmt(statement)
        self.indent -= 1

    def expr(self, node: ast.expr) -> str:
        if isinstance(node, ast.Constant):
            if node.value is None:
                return "py_none()"
            if isinstance(node.value, bool):
                return f"py_bool({'true' if node.value else 'false'})"
            if isinstance(node.value, int):
                return f"py_int({node.value})"
            if isinstance(node.value, float):
                return f"py_float({node.value!r})"
            if isinstance(node.value, str):
                return f"py_str({json.dumps(node.value)})"
            raise CompileError("unsupported literal", node)
        if isinstance(node, ast.Name):
            if node.id not in self.scope.names and node.id not in self.function_names:
                raise CompileError(f"undefined variable '{node.id}'", node)
            return self.ident(node.id)
        if isinstance(node, ast.BinOp):
            functions = {ast.Add: "py_add", ast.Sub: "py_sub", ast.Mult: "py_mul", ast.Div: "py_div", ast.Mod: "py_mod"}
            function = functions.get(type(node.op))
            if not function:
                raise CompileError("unsupported binary operator", node)
            return f"{function}({self.expr(node.left)}, {self.expr(node.right)})"
        if isinstance(node, ast.UnaryOp):
            if isinstance(node.op, ast.USub):
                return f"py_neg({self.expr(node.operand)})"
            if isinstance(node.op, ast.Not):
                return f"py_bool(!{self.condition(node.operand)})"
            if isinstance(node.op, ast.UAdd):
                return self.expr(node.operand)
            raise CompileError("unsupported unary operator", node)
        if isinstance(node, ast.BoolOp):
            op = "&&" if isinstance(node.op, ast.And) else "||"
            return f"py_bool({' {} '.format(op).join(self.condition(value) for value in node.values)})"
        if isinstance(node, ast.Compare):
            return f"py_bool({self.condition(node)})"
        if isinstance(node, ast.Call):
            if not isinstance(node.func, ast.Name) or node.keywords:
                raise CompileError("only direct positional function calls are supported", node)
            if node.func.id == "print":
                raise CompileError("print is only valid as a standalone statement", node)
            if node.func.id not in self.function_names:
                raise CompileError(f"unsupported function '{node.func.id}'", node)
            return f"{self.ident(node.func.id)}({', '.join(self.expr(arg) for arg in node.args)})"
        raise CompileError(f"unsupported expression: {type(node).__name__}", node)

    def condition(self, node: ast.expr) -> str:
        if isinstance(node, ast.Compare):
            if len(node.ops) != 1 or len(node.comparators) != 1:
                raise CompileError("chained comparisons are not supported", node)
            left, right = self.expr(node.left), self.expr(node.comparators[0])
            op = node.ops[0]
            if isinstance(op, ast.Eq): return f"py_eq({left}, {right})"
            if isinstance(op, ast.NotEq): return f"!py_eq({left}, {right})"
            signs = {ast.Lt: "<", ast.LtE: "<=", ast.Gt: ">", ast.GtE: ">="}
            sign = signs.get(type(op))
            if sign: return f"py_num({left}) {sign} py_num({right})"
            raise CompileError("unsupported comparison", node)
        if isinstance(node, ast.BoolOp):
            op = "&&" if isinstance(node.op, ast.And) else "||"
            return f"({' {} '.format(op).join(self.condition(value) for value in node.values)})"
        if isinstance(node, ast.UnaryOp) and isinstance(node.op, ast.Not):
            return f"!({self.condition(node.operand)})"
        return f"py_truth({self.expr(node)})"

    @staticmethod
    def collect_assigned(statements: Iterable[ast.stmt]) -> set[str]:
        """Collect assignments in one lexical scope, excluding nested functions."""
        names: set[str] = set()
        pending: list[ast.AST] = list(statements)
        while pending:
            node = pending.pop()
            if isinstance(node, ast.FunctionDef):
                continue
            if isinstance(node, ast.Assign):
                names.update(target.id for target in node.targets if isinstance(target, ast.Name))
            elif isinstance(node, ast.AugAssign) and isinstance(node.target, ast.Name):
                names.add(node.target.id)
            elif isinstance(node, ast.For) and isinstance(node.target, ast.Name):
                names.add(node.target.id)
            pending.extend(ast.iter_child_nodes(node))
        return names

    @staticmethod
    def ident(name: str) -> str:
        if not name.isidentifier():
            raise CompileError(f"invalid identifier '{name}'")
        return f"py_{name}"

    def emit(self, line: str) -> None:
        prefix = "    " * self.indent
        self.lines.extend((prefix + part if part else "") for part in line.splitlines())
